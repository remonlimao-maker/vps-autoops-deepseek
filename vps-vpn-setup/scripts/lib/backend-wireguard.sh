#!/usr/bin/env bash
# vpnctl backend: WireGuard
#
# Sourced by scripts/vpnctl — do not execute directly.
#
# Layout created on the host:
#   /etc/wireguard/wg0.conf                  rendered from state, never hand-edited
#   /etc/vpnctl/wireguard/meta.env           port, subnet, pubkey, service name
#   /etc/vpnctl/wireguard/server.key         server private key (0600)
#   /etc/vpnctl/wireguard/clients/<n>.env    per-client keys and address
#   /usr/local/lib/vpnctl/wg-nat.sh          NAT helper invoked from PostUp/PostDown
#   /etc/sysctl.d/99-vpnctl.conf             IP forwarding

WG_IFACE="${WG_IFACE:-wg0}"
WG_PORT="${WG_PORT:-51820}"
WG_SUBNET="${WG_SUBNET:-10.66.66.0/24}"
WG_SUBNET6="${WG_SUBNET6:-fd42:66:66::/64}"
WG_MTU="${WG_MTU:-1420}"
WG_DNS="${WG_DNS:-1.1.1.1, 8.8.8.8}"
WG_KEEPALIVE="${WG_KEEPALIVE:-25}"
WG_ROUTE_V6="${WG_ROUTE_V6:-0}"
WG_SPLIT="${WG_SPLIT:-1}"

be_info() { printf 'wireguard|WireGuard|UDP|%s\n' "$WG_PORT"; }

be_parse_opts() {
  while [ "$#" -gt 0 ]; do
    case $1 in
      --port) WG_PORT="${2:-}"; shift 2 ;;
      --subnet) WG_SUBNET="${2:-}"; shift 2 ;;
      --mtu) WG_MTU="${2:-}"; shift 2 ;;
      --dns) WG_DNS="${2:-}"; shift 2 ;;
      --iface) WG_IFACE="${2:-}"; shift 2 ;;
      --keepalive) WG_KEEPALIVE="${2:-}"; shift 2 ;;
      --route-ipv6) WG_ROUTE_V6=1; shift ;;
      --no-split) WG_SPLIT=0; shift ;;
      -h|--help) be_help; exit 0 ;;
      *) die "wireguard: unknown option '$1' (see: vpnctl help)" ;;
    esac
  done
  validate_port "$WG_PORT"
  case $WG_SUBNET in
    *.*.*.*/[0-9]*) ;;
    *) die "wireguard: --subnet must look like 10.66.66.0/24" ;;
  esac
}

# Called by vpnctl for every command once the backend is installed: restore the
# persisted options so client export matches what install produced.
be_from_state() {
  local v
  v="$(meta_get wireguard PORT)";   if [ -n "$v" ]; then WG_PORT="$v"; fi
  v="$(meta_get wireguard SUBNET)"; if [ -n "$v" ]; then WG_SUBNET="$v"; fi
  v="$(meta_get wireguard IFACE)";  if [ -n "$v" ]; then WG_IFACE="$v"; fi
  v="$(meta_get wireguard MTU)";    if [ -n "$v" ]; then WG_MTU="$v"; fi
  v="$(meta_get wireguard DNS)";    if [ -n "$v" ]; then WG_DNS="$v"; fi
  return 0
}

be_help() {
  cat <<EOF
wireguard options:
  --port N          UDP listen port (default $WG_PORT)
  --subnet CIDR     tunnel IPv4 subnet (default $WG_SUBNET)
  --mtu N           tunnel MTU (default $WG_MTU)
  --dns LIST        client DNS (default "$WG_DNS")
  --iface NAME      interface name (default $WG_IFACE)
  --keepalive N     client PersistentKeepalive (default $WG_KEEPALIVE)
  --route-ipv6      route ::/0 through the tunnel (host must have IPv6)
  --no-split        skip generating split-tunnel client variants
EOF
}

validate_port() {
  case $1 in
    ''|*[!0-9]*) die "invalid port: '$1'" ;;
  esac
  if [ "$1" -lt 1 ] || [ "$1" -gt 65535 ]; then die "port out of range: $1"; fi
}

# --- state helpers ---------------------------------------------------------

wg_key_file() { printf '%s/%s/server.key' "$(be_dir wireguard)" "$1"; }
wg_conf_path() { printf '/etc/wireguard/%s.conf' "$WG_IFACE"; }
wg_service() { printf 'wg-quick@%s' "$WG_IFACE"; }
wg_nat_script() { printf '%s/wg-nat.sh' "$VPNCTL_LIB_DIR"; }

wg_netmask() {
  local cidr="${WG_SUBNET#*/}"
  local bits=$((32 - cidr)) mask=0 i=0
  while [ "$i" -lt "$bits" ]; do mask=$(( (mask << 1) | 1 )); i=$((i + 1)); done
  mask=$(( 0xFFFFFFFF ^ mask ))
  printf '%d.%d.%d.%d' $(( (mask >> 24) & 255 )) $(( (mask >> 16) & 255 )) $(( (mask >> 8) & 255 )) $(( mask & 255 ))
}

wg_net_prefix() { local cidr="${WG_SUBNET%/*}"; printf '%s' "${cidr%.*}"; }
wg_server_ip() { printf '%s.1' "$(wg_net_prefix)"; }
wg_prefix_len() { printf '%s' "${WG_SUBNET#*/}"; }

# wg_pubkey PRIVKEY
wg_pubkey() { printf '%s' "$1" | wg pubkey; }

# --- rendering -------------------------------------------------------------

wg_render_server() {
  local key priv pub
  key="$(wg_key_file "$WG_IFACE")"
  [ -r "$key" ] || die "missing server key: $key"
  priv="$(cat "$key")"
  pub="$(meta_get wireguard PUBKEY)"

  printf '# Generated by vpnctl %s — do not edit; re-run `vpnctl install wireguard`\n' "$VPNCTL_VERSION"
  printf '[Interface]\n'
  printf 'Address = %s/%s, %s1/64\n' "$(wg_server_ip)" "$(wg_prefix_len)" "${WG_SUBNET6%::/64}::"
  printf 'ListenPort = %s\n' "$WG_PORT"
  printf 'PrivateKey = %s\n' "$priv"
  printf 'MTU = %s\n' "$WG_MTU"
  printf 'SaveConfig = false\n'
  printf 'PostUp = %s up %%i\n' "$(wg_nat_script)"
  printf 'PostDown = %s down %%i\n' "$(wg_nat_script)"
  printf '\n'

  local n addr cpub psk f
  for f in "$(be_clients_dir wireguard)"/*.env; do
    [ -r "$f" ] || continue
    n="$(basename "$f" .env)"
    addr="$(client_get wireguard "$n" ADDRESS)"
    cpub="$(client_get wireguard "$n" PUBKEY)"
    psk="$(client_get wireguard "$n" PSK)"
    [ -n "$cpub" ] || continue
    printf '# client: %s\n[Peer]\n' "$n"
    printf 'PublicKey = %s\n' "$cpub"
      if [ -n "$psk" ]; then printf 'PresharedKey = %s\n' "$psk"; fi
    printf 'AllowedIPs = %s/32' "$addr"
    if [ "$WG_ROUTE_V6" = "1" ]; then
      printf ', %s/128' "$(client_get wireguard "$n" ADDRESS6)"
    fi
    printf '\n\n'
  done
}

# wg_client_conf NAME VARIANT(full|split)
wg_client_conf() {
  local name="$1" variant="${2:-full}" priv addr addr6 pub psk endpoint allowed
  priv="$(client_get wireguard "$name" PRIVKEY)"
  addr="$(client_get wireguard "$name" ADDRESS)"
  addr6="$(client_get wireguard "$name" ADDRESS6)"
  pub="$(meta_get wireguard PUBKEY)"
  psk="$(client_get wireguard "$name" PSK)"
  endpoint="$(meta_get wireguard ENDPOINT)"
  if [ -z "$endpoint" ]; then endpoint="$(meta_get wireguard PUBLIC_IP):$(meta_get wireguard PORT)"; fi

  if [ "$variant" = "split" ]; then
    allowed="$(meta_get wireguard SUBNET)"
  else
    allowed="0.0.0.0/0"
    if [ "$WG_ROUTE_V6" = "1" ]; then allowed="0.0.0.0/0, ::/0"; fi
  fi

  printf '# %s — %s tunnel — generated by vpnctl\n' "$name" "$variant"
  printf '[Interface]\n'
  printf 'PrivateKey = %s\n' "$priv"
  if [ -n "$addr6" ]; then printf 'Address = %s/32, %s/128\n' "$addr" "$addr6"; else printf 'Address = %s/32\n' "$addr"; fi
  printf 'DNS = %s\n' "$WG_DNS"
  printf 'MTU = %s\n' "$WG_MTU"
  printf '\n[Peer]\n'
  printf 'PublicKey = %s\n' "$pub"
  if [ -n "$psk" ]; then printf 'PresharedKey = %s\n' "$psk"; fi
  printf 'Endpoint = %s\n' "$endpoint"
  printf 'AllowedIPs = %s\n' "$allowed"
  printf 'PersistentKeepalive = %s\n' "$WG_KEEPALIVE"
}

# --- plan ------------------------------------------------------------------

be_print_plan() {
  cat <<EOF
Plan: WireGuard on this host
  1. install   wireguard-tools (+ iptables, qrencode) via $(pkg_manager)
  2. check     kernel module 'wireguard' (or fail with a userspace alternative)
  3. generate  server keypair -> $(be_dir wireguard)/server.key
  4. write     $(wg_conf_path)  (interface $WG_IFACE, port $WG_PORT, subnet $WG_SUBNET)
  5. enable    sysctl net.ipv4.ip_forward + $(wg_nat_script) (MASQUERADE on the default route)
  6. start     systemd unit $(wg_service)
  7. verify    wg handshake state, listening UDP/$WG_PORT

Clients are added later:
  vpnctl client wireguard add --name phone --yes
EOF
}

# --- install ---------------------------------------------------------------

be_install() {
  case "$(virt_kind)" in
    lxc|lxd|openvz|docker)
      log_err "virt=$(virt_kind): WireGuard needs the kernel module and /dev/net/tun, which this container usually cannot provide."
      log_info "use a TCP backend instead:  vpnctl install xray-reality --yes"
      return 2
      ;;
  esac

  ensure_pkgs wireguard-tools iptables qrencode
  have wg || die "wg not found after install; check your package manager"
  have wg-quick || die "wg-quick not found after install"

  if ! modprobe wireguard 2>/dev/null; then
    if [ ! -d /sys/module/wireguard ]; then
      log_err "kernel module 'wireguard' is unavailable on $(uname -r) ($(detect_os; printf '%s' "$OS_NAME"))."
      log_info "Ubuntu/Debian: apt-get install wireguard-dkms (needs kernel headers) or upgrade the kernel."
      return 2
    fi
  fi

  meta_init wireguard

  if port_listening "$WG_PORT" udp && ! svc_active "$(wg_service)"; then
    log_err "UDP/$WG_PORT is already in use:"
    port_owner_hint "$WG_PORT" >&2 || true
    die "pick another port with --port"
  fi

  # server keypair (stable across re-runs)
  local key; key="$(wg_key_file "$WG_IFACE")"
  if [ ! -r "$key" ]; then
    ( umask 077; mkdir -p "$(dirname "$key")"; wg genkey > "$key" )
    log_ok "generated server key: $key"
  fi
  local pub; pub="$(wg_pubkey "$(cat "$key")")"

  # endpoint must be reachable from clients: prefer the public address
  local ip; ip="$(public_ipv4 || true)"
  if [ -z "$ip" ]; then
    log_warn "could not detect the public IPv4; using the local address (fix later in $(be_meta wireguard) ENDPOINT)"
    ip="$(local_ipv4 || true)"
  fi
  [ -n "$ip" ] || die "cannot determine the host address; pass it via WG_ENDPOINT"
  local endpoint="${WG_ENDPOINT:-$ip:$WG_PORT}"

  meta_set wireguard PORT "$WG_PORT"
  meta_set wireguard SUBNET "$WG_SUBNET"
  meta_set wireguard SUBNET6 "$WG_SUBNET6"
  meta_set wireguard PUBLIC_IP "$ip"
  meta_set wireguard ENDPOINT "$endpoint"
  meta_set wireguard PUBKEY "$pub"
  meta_set wireguard IFACE "$WG_IFACE"
  meta_set wireguard MTU "$WG_MTU"
  meta_set wireguard DNS "$WG_DNS"
  meta_set wireguard SERVICE "$(wg_service)"
  meta_set wireguard CONFIG "$(wg_conf_path)"

  # forwarding + NAT helper
  {
    printf '# managed by vpnctl\n'
    printf 'net.ipv4.ip_forward = 1\n'
    if [ "$WG_ROUTE_V6" = "1" ]; then printf 'net.ipv6.conf.all.forwarding = 1\n'; fi
  } > /tmp/vpnctl-sysctl.$$
  install_file /tmp/vpnctl-sysctl.$$ /etc/sysctl.d/99-vpnctl.conf 0644
  rm -f /tmp/vpnctl-sysctl.$$
  run sysctl --system >/dev/null 2>&1 || run sysctl -p /etc/sysctl.d/99-vpnctl.conf >/dev/null 2>&1 || true

  wg_write_nat_helper

  # render + install server config
  wg_render_server > /tmp/vpnctl-wg.$$
  install_file /tmp/vpnctl-wg.$$ "$(wg_conf_path)" 0600
  rm -f /tmp/vpnctl-wg.$$

  svc_enable_now "$(wg_service)"

  if ! wait_for_port "$WG_PORT" udp 10; then
    log_warn "UDP/$WG_PORT not observed in 'ss' yet; WireGuard may still be fine (check 'wg show')"
  fi
  log_ok "WireGuard up on $(wg_conf_path) (port $WG_PORT)"
}

wg_write_nat_helper() {
  local tmp="/tmp/vpnctl-nat.$$"
  cat > "$tmp" <<'NAT'
#!/bin/sh
# Installed by vpnctl: NAT/forwarding rules for a WireGuard interface.
# Called from PostUp/PostDown in the wg config, so it is re-applied on boot.
set -eu
action="${1:?up|down required}"
tun="${2:?interface required}"
net="__VPNCTL_SUBNET__"

wan="$(ip -4 route show default 2>/dev/null | awk '/default/ {print $5; exit}')"
[ -n "${wan:-}" ] || { echo "wg-nat: no default route; skipping" >&2; exit 0; }

ipt() { iptables -w "$@"; }

case "$action" in
  up)
    ipt -t nat -C POSTROUTING -s "$net" -o "$wan" -j MASQUERADE 2>/dev/null || \
      ipt -t nat -A POSTROUTING -s "$net" -o "$wan" -j MASQUERADE
    ipt -C FORWARD -i "$tun" -j ACCEPT 2>/dev/null || ipt -A FORWARD -i "$tun" -j ACCEPT
    ipt -C FORWARD -o "$tun" -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT 2>/dev/null || \
      ipt -A FORWARD -o "$tun" -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
    ;;
  down)
    ipt -t nat -D POSTROUTING -s "$net" -o "$wan" -j MASQUERADE 2>/dev/null || true
    ipt -D FORWARD -i "$tun" -j ACCEPT 2>/dev/null || true
    ipt -D FORWARD -o "$tun" -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT 2>/dev/null || true
    ;;
  *) echo "wg-nat: unknown action $action" >&2; exit 2 ;;
esac
NAT
  sed -i "s|__VPNCTL_SUBNET__|$WG_SUBNET|g" "$tmp"
  install_file "$tmp" "$(wg_nat_script)" 0755
  rm -f "$tmp"
}

# --- clients ---------------------------------------------------------------

wg_next_ip() {
  local base used i cand
  base="$(wg_net_prefix)"
  used="$(client_list wireguard | while read -r n; do client_get wireguard "$n" ADDRESS; done)"
  i=2
  while [ "$i" -le 254 ]; do
    cand="$base.$i"
    if ! printf '%s\n' "$used" | grep -qx "$cand"; then printf '%s' "$cand"; return 0; fi
    i=$((i + 1))
  done
  return 1
}

wg_next_ip6() {
  local used i cand
  used="$(client_list wireguard | while read -r n; do client_get wireguard "$n" ADDRESS6; done)"
  i=2
  while [ "$i" -le 254 ]; do
    cand="fd42:66:66::$i"
    if ! printf '%s\n' "$used" | grep -qx "$cand"; then printf '%s' "$cand"; return 0; fi
    i=$((i + 1))
  done
  return 1
}

be_client_add() {
  local name="$1"
  local addr addr6 priv pub psk tmpd
  addr="$(wg_next_ip)" || die "no free address left in $WG_SUBNET"
  addr6="$(wg_next_ip6 || true)"
  tmpd="$(mktemp -d)"
  ( umask 077
    wg genkey > "$tmpd/priv"
    wg genpsk > "$tmpd/psk"
    wg pubkey < "$tmpd/priv" > "$tmpd/pub"
  )
  priv="$(cat "$tmpd/priv")"; pub="$(cat "$tmpd/pub")"; psk="$(cat "$tmpd/psk")"
  rm -rf "$tmpd"

  client_write wireguard "$name" \
    "ADDRESS=$addr" \
    "ADDRESS6=$addr6" \
    "PRIVKEY=$priv" \
    "PUBKEY=$pub" \
    "PSK=$psk" \
    "CREATED=$(date -u +%Y-%m-%dT%H:%M:%SZ)"

  wg_render_server > /tmp/vpnctl-wg.$$
  install_file /tmp/vpnctl-wg.$$ "$(wg_conf_path)" 0600
  rm -f /tmp/vpnctl-wg.$$
  wg_sync
  log_ok "added client $name ($addr)"
}

wg_sync() {
  if ! svc_active "$(wg_service)"; then
    svc_enable_now "$(wg_service)"
    return 0
  fi
  if [ "$DRY_RUN" = "1" ]; then
    log_cmd wg syncconf "$WG_IFACE" "<(wg-quick strip $WG_IFACE)"
    return 0
  fi
  wg-quick strip "$WG_IFACE" > "/tmp/vpnctl-sync.$$"
  if ! wg syncconf "$WG_IFACE" "/tmp/vpnctl-sync.$$"; then
    rm -f "/tmp/vpnctl-sync.$$"
    log_warn "wg syncconf failed; restarting the service instead"
    run systemctl restart "$(wg_service)"
    return 0
  fi
  rm -f "/tmp/vpnctl-sync.$$"
  log_debug "synced live peers"
}

be_client_remove() {
  local name="$1"
  rm -f "$(client_file wireguard "$name")"
  wg_render_server > /tmp/vpnctl-wg.$$
  install_file /tmp/vpnctl-wg.$$ "$(wg_conf_path)" 0600
  rm -f /tmp/vpnctl-wg.$$
  wg_sync
}

be_client_export() {
  local name="$1" outdir="${2:-}" dir
  if [ -z "$outdir" ]; then dir="${HOME:-/root}/vpn-clients/wireguard/$name"; else dir="$outdir"; fi
  mkdir -p "$dir"

  wg_client_conf "$name" full > "$dir/$name.conf"
  chmod 600 "$dir/$name.conf"
  printf '%s\n' "$dir/$name.conf"

  if [ "$WG_SPLIT" = "1" ]; then
    wg_client_conf "$name" split > "$dir/$name-split.conf"
    chmod 600 "$dir/$name-split.conf"
    printf '%s\n' "$dir/$name-split.conf"
  fi

  {
    printf 'backend: wireguard\n'
    printf 'client:  %s\n' "$name"
    printf 'address: %s\n' "$(client_get wireguard "$name" ADDRESS)"
    printf 'server:  %s\n' "$(meta_get wireguard PUBKEY)"
    printf 'endpoint:%s\n' "$(meta_get wireguard ENDPOINT)"
    printf 'created: %s\n' "$(client_get wireguard "$name" CREATED)"
    printf '\nImport: WireGuard app -> "Import from file or archive" -> %s.conf\n' "$name"
    printf 'QR:     qrencode -t ansiutf8 < %s.conf\n' "$name"
  } > "$dir/info.txt"

  if have qrencode; then
    qrencode -o "$dir/$name.png" -r "$dir/$name.conf" 2>/dev/null \
      && printf '%s\n' "$dir/$name.png" \
      || log_warn "qrencode failed"
  fi

  log_ok "client files in $dir"
}

# --- verify / uninstall ----------------------------------------------------

be_verify() {
  local ok=1 service conf
  service="$(meta_get wireguard SERVICE)"; conf="$(wg_conf_path)"
  local checks=""

  if svc_active "$service"; then checks="$checks service=up"; else checks="$checks service=down"; ok=0; fi
  if wg show "$WG_IFACE" >/dev/null 2>&1; then checks="$checks interface=up"; else checks="$checks interface=down"; ok=0; fi
  if [ -r "$conf" ]; then checks="$checks config=present"; else checks="$checks config=missing"; ok=0; fi
  if port_listening "$WG_PORT" udp; then checks="$checks udp=$WG_PORT"; else checks="$checks udp=unconfirmed"; fi
  local fwd; fwd="$(sysctl -n net.ipv4.ip_forward 2>/dev/null || printf 0)"
  if [ "$fwd" = "1" ]; then checks="$checks ip_forward=1"; else checks="$checks ip_forward=0"; log_warn "IP forwarding is off: clients cannot reach the internet"; fi

  local peers=0 handshakes=0
  if have wg; then
    peers="$(wg show "$WG_IFACE" peers 2>/dev/null | wc -l | tr -d ' ')"
    handshakes="$(wg show "$WG_IFACE" latest-handshakes 2>/dev/null | awk '$2 > 0' | wc -l | tr -d ' ')"
    checks="$checks peers=$peers handshaked=$handshakes"
  fi

  if [ "$JSON_OUT" = "1" ]; then
    printf '{"backend":"wireguard","ok":%s,"checks":%s,"peers":%s,"handshaked":%s,"endpoint":%s}\n' \
      "$([ "$ok" = "1" ] && printf true || printf false)" \
      "$(json_str "${checks# }")" "$peers" "$handshakes" "$(json_str "$(meta_get wireguard ENDPOINT)")"
  else
    printf 'wireguard: %s\n' "$([ "$ok" = "1" ] && echo OK || echo FAILED)"
    printf '  %s\n' "${checks# }"
  fi
  [ "$ok" = "1" ]
}

be_uninstall() {
  local service; service="$(meta_get wireguard SERVICE)"
  if [ -n "$service" ]; then svc_stop_disable "$service"; fi
  if [ -f "$(wg_conf_path)" ]; then backup_file "$(wg_conf_path)" >/dev/null; run rm -f "$(wg_conf_path)"; fi
  # remove NAT rules that PostDown may not have reached while stopping
  run sh "$(wg_nat_script)" down "$WG_IFACE" >/dev/null 2>&1 || true
  run rm -f "$(wg_nat_script)"
  log_ok "WireGuard removed (state kept)"
}
